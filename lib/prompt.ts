// 자료 조각을 AI가 읽기 좋은 글로 만든다.
function formatSources(sources: readonly OdaSource[]): string {
  return sources
    .map(
      (source) =>
        `[${source.id}] ${source.org} · ${source.title} (기준일 ${source.asOf})\n${source.text}`
    )
    .join("\n\n");
}

export type ChatMessage = { role: "system" | "user"; content: string };

// 질문 속에 "[자료]", "[질문]", "[출처: …]", "[S1]" 같은 우리 표지가 들어 있으면 지운다.
// (가짜 자료를 끼워 넣어 지어낸 내용에 진짜 출처가 붙게 만드는 시도를 막는다. Check 보안 점검 4번)
export function sanitizeQuestion(question: string): string {
  return question.replace(/\[\s*(?:자료|질문|출처|S\d+)[^\]\n]*\]?/gi, " ").replace(/[ \t]{2,}/g, " ").trim();
}

// 자료는 "시스템 메시지"로, 사용자가 쓴 질문은 "사용자 메시지"로 따로 보낸다.
// 둘을 한 메시지에 이어 붙이면 사용자가 자료인 척하는 글을 끼워 넣기 쉬워진다.
export function buildMessages(
  question: string,
  sources: readonly OdaSource[]
): ChatMessage[] {
  return [
    { role: "system", content: SYSTEM_PROMPT },
    { role: "system", content: `[자료]\n${formatSources(sources)}` },
    {
      role: "user",
      // 질문 바로 뒤에 우리가 붙이는 상기 문구. (모델에 따라 맨 끝 출처 줄을 빠뜨리는 일이 있어 한 번 더 알려 준다)
      content: `[질문]\n${sanitizeQuestion(question)}\n\n[답변할 때 지킬 것] 답변은 5문장 이내로 쓰고, 용어 풀이표에 있는 용어(증여등가액, 양자원조, 다자원조, 유상원조, 무상원조, 차관, 주관기관, 시행기관 등)가 나오면 처음 한 번 바로 뒤에 괄호로 풀이를 붙입니다. 자료로 답했다면 마지막 줄에 [출처: S번호] 줄을 반드시 적고, 정해진 문장으로 답할 때는 적지 않습니다.`,
    },
  ];
}
